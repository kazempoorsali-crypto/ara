    import time
    done = set(store.get_setting("seeded_articles") or [])
    now = int(time.time())
    new = [a for a in ARTICLES if a["slug"] not in done]
    for i, a in enumerate(new):
        exists = store.q("SELECT 1 FROM articles WHERE slug=?", (a["slug"],), one=True)
        if not exists:
            store.x("INSERT INTO articles(slug,title,summary,body,city_key,published,created,updated) VALUES(?,?,?,?,?,?,?,?)",
                    (a["slug"], a["title"], a["summary"], a["body"], None, 1, now - i, now - i))
        done.add(a["slug"])
    if new:
        store.set_setting("seeded_articles", sorted(done))
